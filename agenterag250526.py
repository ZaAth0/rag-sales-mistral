"""Sistema Unificado"""

class AsistenteVentas:
    def __init__(self, agent, rag, df, retriever):
        self.agent = agent
        self.rag = rag
        self.df = df
        self.retriever = retriever
        self.historial = []

    def preguntar(self, pregunta):
        # Decisión de método
        keywords_agente = [
            'total', 'promedio', 'suma', 'máximo', 'mínimo',
            'top', 'ranking', 'porcentaje', 'agrupar', 'distribución',
            'estadística', 'cuántos', 'cuántas', 'contar'
        ]

        pregunta_lower = pregunta.lower()
        metodo = "rag"

        if any(kw in pregunta_lower for kw in keywords_agente):
            metodo = "agente"

        if metodo == "agente":
            try:
                resp = self.agent.invoke(pregunta)
                respuesta = str(resp['output']) if isinstance(resp, dict) else str(resp)
                fuentes = None
            except Exception as e:
                # Fallback a RAG con retriever
                respuesta, fuentes, docs = self.rag.consultar(pregunta)
                metodo = "rag (fallback)"
        else:
            respuesta, fuentes, docs = self.rag.consultar(pregunta)

        self.historial.append({
            "pregunta": pregunta,
            "respuesta": respuesta,
            "metodo": metodo,
            "num_docs": len(fuentes) if fuentes else 0
        })

        return respuesta, metodo

