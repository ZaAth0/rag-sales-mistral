from langchain_core.documents import Document

def crear_corpus(df, max_reg=500):
    docs = []
    for idx, row in df.head(max_reg).iterrows():
        texto = f"""VENTA #{row['ORDERNUMBER']}
Producto: {row['PRODUCTLINE']} | Cantidad: {int(row['QUANTITYORDERED'])}
Venta: ${row['SALES']:.2f} | Estado: {row['STATUS']}
País: {row['COUNTRY']} | Fecha: {row['ORDERDATE'].date()}
Tamaño: {row['DEALSIZE']} | Cliente: {row['CUSTOMERNAME']}"""

        docs.append(Document(
            page_content=texto,
            metadata={
                "order": int(row['ORDERNUMBER']),
                "sales": float(row['SALES']),
                "country": row['COUNTRY'],
                "status": row['STATUS'],
                "product": row['PRODUCTLINE']
            }
        ))
    return docs

corpus = crear_corpus(df, max_reg=500)
print(f"✓ Corpus: {len(corpus)} documentos")

