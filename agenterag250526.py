from langchain_mistralai import ChatMistralAI
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_core.runnables import RunnablePassthrough

class RAGMistral:
    def __init__(self, retriever, api_key, model="mistral-small-latest"):
        self.retriever = retriever
        self.client = Mistral(api_key=api_key)
        self.model = model

        # Template para el prompt
        self.prompt_template = """Eres un analista de ventas experto.
Responde SOLO con datos del contexto proporcionado.

CONTEXTO RECUPERADO:
{context}

PREGUNTA DEL USUARIO:
{question}

INSTRUCCIONES:
- Usa solo información del contexto
- Cita números de orden y montos específicos
- Si no hay suficiente información, indícalo claramente
- Responde en español

RESPUESTA:"""

    def formatear_docs(self, docs):
        """Formatea los documentos recuperados en un solo texto"""
        return "\n\n---\n\n".join([doc.page_content for doc in docs])

    def consultar(self, pregunta):
        # 1. RECUPERAR documentos relevantes usando el retriever
        docs_relevantes = self.retriever.invoke(pregunta)

        # 2. Formatear contexto
        contexto = self.formatear_docs(docs_relevantes)

        # 3. Crear prompt completo
        prompt_completo = self.prompt_template.format(
            context=contexto,
            question=pregunta
        )

        # 4. Generar respuesta con Mistral
        response = self.client.chat.complete(
            model=self.model,
            messages=[
                {"role": "system", "content": "Eres un analista de ventas experto."},
                {"role": "user", "content": prompt_completo}
            ],
            temperature=0.2,
            max_tokens=500
        )

        respuesta = response.choices[0].message.content

        # 5. Extraer fuentes
        fuentes = []
        for doc in docs_relevantes:
            fuentes.append({
                "order": doc.metadata.get('order'),
                "sales": doc.metadata.get('sales'),
                "country": doc.metadata.get('country'),
                "status": doc.metadata.get('status'),
                "product": doc.metadata.get('product')
            })

        return respuesta, fuentes, docs_relevantes

rag = RAGMistral(retriever, API_KEY)
